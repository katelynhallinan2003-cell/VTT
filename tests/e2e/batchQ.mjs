// Round 6a: picture tools menu, real HP numbers for players, drawings following the panel's colours live.
import { launch, watch, sleep } from './lib.mjs';
import { mkdirSync } from 'node:fs';
const BASE = (process.env.BASE || 'http://127.0.0.1:4174/') + '?demo';
const errors = [];
const results = [];
const check = (name, ok, extra = '') => { results.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? '  ' + extra : ''}`); };
mkdirSync('/tmp/shots', { recursive: true });
const { browser, context } = await launch();
const dm = await context.newPage();
watch(dm, 'dm', errors);
await dm.goto(BASE);
await dm.evaluate(() => localStorage.clear());
await dm.reload();
await dm.getByRole('button', { name: /Start as the DM/ }).click();
await dm.getByPlaceholder('New table name').fill('Q');
await dm.getByRole('button', { name: 'Create table' }).click();
await dm.waitForSelector('.board-host canvas');
await dm.getByRole('button', { name: '+ New scene' }).first().click();
await dm.getByRole('button', { name: 'Use sample dungeon' }).click();
await dm.locator('.modal .muted', { hasText: 'Sample dungeon.png' }).waitFor();
await dm.getByRole('button', { name: 'Create scene' }).click();
await dm.waitForFunction(() => window.__vtt?.board?.mapSprite);
await sleep(400);
const grid = await dm.evaluate(() => ({ ...window.__vtt.client.grid }));
const cell = grid.cell;
const gx = (i) => grid.ox + i * cell;
const gy = (j) => grid.oy + j * cell;
const screen = (wx, wy) => dm.evaluate(([x, y]) => window.__vtt.board.worldToScreen({ x, y }), [wx, wy]);
const draws = () => dm.evaluate(() => [...window.__vtt.client.scene.draws.values()].map((d) => ({ ...d })));
const drag = async (a, b) => {
  const p = await screen(a[0], a[1]), q = await screen(b[0], b[1]);
  await dm.mouse.move(p.x, p.y); await dm.mouse.down();
  await dm.mouse.move((p.x + q.x) / 2, (p.y + q.y) / 2, { steps: 5 });
  await dm.mouse.move(q.x, q.y, { steps: 6 }); await dm.mouse.up(); await sleep(350);
};

// ---- drawings follow the panel while they are selected
await dm.keyboard.press('d');
await dm.locator('.flyout-title', { hasText: /^Draw$/ }).waitFor();
await dm.locator('.flyout .seg button', { hasText: /^Box$/ }).click();
const tool = await dm.evaluate(() => window.__vtt.ui.data.drawTool);
console.log('draw tool', tool);
await drag([gx(12), gy(3)], [gx(15), gy(5)]);
let ds = await draws();
check('drawing something selects it', ds.length === 1 && (await dm.evaluate(() => window.__vtt.ui.data.drawSel.size)) === 1, `${ds.length} drawings, tool ${tool}`);
const c0 = ds[0].color;
const swatches = dm.locator('.flyout .swatches .swatch');
const n = await swatches.count();
await swatches.nth(Math.min(3, n - 1)).click();
await sleep(400);
ds = await draws();
check('picking another colour recolours the selected drawing straight away', ds[0].color !== c0, `${c0} -> ${ds[0].color}`);
const wBefore = ds[0].w;
await dm.locator('.flyout .seg button', { hasText: /^Thick$/ }).click();
await sleep(400);
ds = await draws();
check('so does the stroke size', ds[0].w > wBefore, `${wBefore} -> ${ds[0].w}`);
check('and the panel says so', (await dm.locator('.flyout .hint', { hasText: 'still selected' }).count()) === 1);
const toggle = dm.locator('.flyout label', { hasText: 'Dashed' }).locator('input');
await toggle.check();
await sleep(300);
check('dashed applies live too', (await draws())[0].dash === true);
await dm.keyboard.press('Control+z');
await sleep(300);
check('and one Ctrl+Z takes back a change', (await draws())[0].dash !== true);
// a second drawing is drawn in the new colours, and the first is no longer touched
await drag([gx(12), gy(7)], [gx(15), gy(9)]);
ds = await draws();
const first = ds.find((d) => d.p.startsWith(String(Math.round(gx(12)))) || true);
const colorsBefore = ds.map((d) => d.color).join();
await swatches.nth(0).click();
await sleep(300);
ds = await draws();
check('after drawing a second one only that one follows the panel', ds.filter((d) => d.color === ds[0].color).length >= 1 && ds.map((d) => d.color).join() !== colorsBefore);
await dm.keyboard.press('Escape');
await dm.keyboard.press('v');

// ---- real numbers for players
const orc = await dm.evaluate(([x, y]) => window.__vtt.client.addToken({ x, y, name: 'Orc', hp: 30, maxHp: 30 }), [gx(5.5), gy(5.5)]);
await sleep(500);
await dm.evaluate((id) => window.__vtt.ui.select([id]), orc);
await dm.keyboard.press('e');
await dm.locator('.modal').waitFor();
const sel = dm.locator('.modal select', { has: dm.locator('option[value="numbers"]') });
check('the health setting has a fourth option with the real numbers', (await sel.count()) === 1 && (await sel.locator('option').count()) === 4);
await sel.selectOption('numbers');
await dm.locator('.modal .btn.primary', { hasText: 'Save' }).click();
await sleep(600);
const pub = await dm.evaluate((id) => { const t = window.__vtt.client.scene.tokens.get(id); return { hpShow: t.hpShow, hpNow: t.hpNow, hpCap: t.hpCap, hpPct: t.hpPct }; }, orc);
check('saving it publishes the numbers to the players\' copy', pub.hpShow === 'numbers' && pub.hpNow === 30 && pub.hpCap === 30 && pub.hpPct === 100, JSON.stringify(pub));
await dm.evaluate((id) => window.__vtt.client.damage([id], 11), orc);
await sleep(500);
const pub2 = await dm.evaluate((id) => { const t = window.__vtt.client.scene.tokens.get(id); return { hpNow: t.hpNow, hpPct: t.hpPct }; }, orc);
check('damage keeps them current', pub2.hpNow === 19 && pub2.hpPct === 63, JSON.stringify(pub2));
// what a player sees on the board
await dm.evaluate(() => window.__vtt.ui.set({ dmPreview: true }));
await sleep(500);
const label = await dm.evaluate((id) => window.__vtt.board.views.get(id)?.hpText?.text, orc);
check('the board draws "19/30" on the health bar in the player\'s view', label === '19/30', String(label));
await dm.evaluate((id) => window.__vtt.ui.select([id]), orc);
const sub = await dm.locator('.dock').innerText();
await dm.evaluate(() => window.__vtt.ui.set({ dmPreview: false }));
await sleep(300);
const labelDm = await dm.evaluate((id) => window.__vtt.board.views.get(id)?.hpText?.text, orc);
check('the DM\'s own view has no numbers on the bar (they are in the panel)', labelDm === '', String(labelDm));
await dm.screenshot({ path: '/tmp/shots/q1-hp.png' });

// ---- picture tools hold Replace and Remove
const pic = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==';
await dm.evaluate(([id, img]) => window.__vtt.client.updateToken(id, { img }), [orc, pic]);
await sleep(400);
await dm.evaluate((id) => window.__vtt.ui.select([id]), orc);
await dm.keyboard.press('e');
await dm.locator('.modal').waitFor();
await sleep(500);
const has = async (name) => dm.locator('.modal button, .modal label', { hasText: name }).count();
check('a token with a picture hides Replace and Remove until picture tools are open', (await has('Replace picture')) === 0 && (await has('Remove picture')) === 0 && (await has('Picture tools')) === 1);
await dm.locator('.modal button', { hasText: 'Picture tools' }).click();
await sleep(300);
check('opening picture tools shows both', (await has('Replace picture')) >= 1 && (await has('Remove picture')) === 1);
await dm.locator('.modal button', { hasText: 'Hide picture tools' }).click();
await sleep(200);
check('and closing them hides them again', (await has('Replace picture')) === 0);
await dm.locator('.modal button', { hasText: 'Cancel' }).click();
await dm.evaluate((id) => window.__vtt.client.updateToken(id, { img: null }), orc);
await sleep(300);
await dm.evaluate((id) => window.__vtt.ui.select([id]), orc);
await dm.keyboard.press('e');
await dm.locator('.modal').waitFor();
await sleep(300);
check('a token with no picture still offers Add picture straight away', (await has('Add picture')) >= 1);
await dm.locator('.modal button', { hasText: 'Cancel' }).click();

const bad = errors.filter((e) => !/GPU stall|ReadPixels|willReadFrequently/.test(e));
console.log('\nerrors:', bad.join('\n') || 'none');
console.log(`${results.filter(Boolean).length}/${results.length} passed`);
await browser.close();
process.exit(results.every(Boolean) && !bad.length ? 0 : 1);
