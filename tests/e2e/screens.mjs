import { launch, watch, sleep } from './lib.mjs';
const BASE = 'http://127.0.0.1:5173/?demo';
const errors = [];
const { browser, context } = await launch();
const dm = await context.newPage();
watch(dm, 'dm', errors);
await dm.goto(BASE);
await dm.screenshot({ path: '/tmp/shots/20-home.png' });
await dm.getByRole('button', { name: /Start as the DM/ }).click();
await dm.getByPlaceholder('New table name').fill('Friday campaign');
await dm.screenshot({ path: '/tmp/shots/21-home-signed.png' });
await dm.getByRole('button', { name: 'Create table' }).click();
await dm.waitForSelector('.board-host canvas');
await sleep(300);
await dm.screenshot({ path: '/tmp/shots/22-empty-table.png' });
await dm.getByRole('button', { name: '+ New scene' }).first().click();
await dm.screenshot({ path: '/tmp/shots/23-new-scene.png' });
await dm.getByRole('button', { name: 'Use sample dungeon' }).click();
await dm.getByRole('button', { name: 'Create scene' }).waitFor();
await dm.locator('.modal .muted', { hasText: 'Sample dungeon.png' }).waitFor();
await dm.getByRole('button', { name: 'Create scene' }).click();
await dm.waitForFunction(() => window.__vtt?.board?.mapSprite);
const tid = await dm.evaluate(() => location.hash.replace('#/t/', ''));
await dm.getByRole('button', { name: 'Settings' }).click();
await sleep(200);
await dm.screenshot({ path: '/tmp/shots/24-settings.png' });
await dm.keyboard.press('Escape');
await dm.keyboard.press('f');
await sleep(300);
await dm.screenshot({ path: '/tmp/shots/25-fog-tool.png' });
const pl = await context.newPage();
watch(pl, 'pl', errors);
await pl.goto(`${BASE}#/t/${tid}`);
await pl.screenshot({ path: '/tmp/shots/26-join.png' });
console.log(errors.filter((e) => !/GL Driver|404/.test(e)).join('\n') || 'no errors');
await browser.close();
