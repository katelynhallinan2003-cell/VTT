import { launch, watch, sleep } from './lib.mjs';
const BASE = 'http://127.0.0.1:5173/?demo';
const errors = [];
const { browser, context } = await launch();
const dm = await context.newPage();
watch(dm, 'dm', errors);
await dm.goto(BASE);
await dm.getByRole('button', { name: /Start as the DM/ }).click();
await dm.getByPlaceholder('New table name').fill('Tokens');
await dm.getByRole('button', { name: 'Create table' }).click();
await dm.waitForSelector('.board-host canvas');
await dm.getByRole('button', { name: '+ New scene' }).first().click();
await dm.getByRole('button', { name: 'Use sample dungeon' }).click();
await dm.getByRole('button', { name: 'Create scene' }).waitFor();
await dm.locator('.modal .muted', { hasText: 'Sample dungeon.png' }).waitFor();
await dm.getByRole('button', { name: 'Create scene' }).click();
await dm.waitForFunction(() => window.__vtt?.board?.mapSprite);
const ids = await dm.evaluate(async () => {
  const m = await import('/src/core/sample.ts');
  const c = window.__vtt.client;
  const mk = async (l, col) => URL.createObjectURL(await m.makeSampleToken(l, col));
  const out = [];
  out.push(await c.addToken({ x: 245, y: 245, name: 'Circle', img: await mk('Ci', '#e8590c'), shape: 'circle', ring: '#4dabf7', ringW: 0.08, size: 1 }));
  out.push(await c.addToken({ x: 455, y: 245, name: 'Square', img: await mk('Sq', '#2f9e44'), shape: 'square', ring: '#ffd43b', ringW: 0.06, size: 1 }));
  out.push(await c.addToken({ x: 735, y: 315, name: 'Large dragon', img: await mk('Dr', '#9c36b5'), shape: 'circle', ring: '#ff6b6b', size: 2 }));
  out.push(await c.addToken({ x: 245, y: 455, name: 'Frameless', img: await mk('Fr', '#1971c2'), shape: 'none', size: 1 }));
  out.push(await c.addToken({ x: 385, y: 455, name: 'Tiny', img: null, shape: 'circle', size: 0.5 }));
  return out;
});
await sleep(1500);
await dm.evaluate(() => { const b = window.__vtt.board; b.cam = { zoom: 1.6, tx: -80, ty: -80 }; b.applyCamera(); });
await dm.evaluate((ids) => window.__vtt.ui.select([ids[0]]), ids);
await sleep(600);
await dm.screenshot({ path: '/tmp/shots/10-tokens.png', clip: { x: 0, y: 40, width: 1000, height: 600 } });
console.log(errors.filter((e) => !/GL Driver|404/.test(e)).join('\n') || 'no errors');
await browser.close();
